#!/usr/bin/env python3
"""Generate src/graphics/kitty_diacritics.rs, the row/column diacritic table for kitty
Unicode image placeholders, clean-room from the Unicode Character Database.

Provenance: the table is regenerated here from UCD 6.0.0 `UnicodeData.txt` (unicode.org) by
the selection rule the kitty graphics protocol documentation states in words:

    Unicode 6.0.0 characters with General_Category Mn, Canonical_Combining_Class 230,
    Bidi_Class NSM and no decomposition mapping, minus 19 characters that normalization may
    fuse with a base: U+0300-0304, U+0306-030C, U+030F, U+0311, U+0313, U+0314, U+0342,
    U+0653, U+0654.

No kitty source or data file is copied. See docs/design/v0.9-kitty-graphics-route.md, §16.

Usage (the UCD file is not committed; fetch it, then run):
    curl -sSfLo UnicodeData.txt https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt
    python3 scripts/gen_kitty_diacritics.py UnicodeData.txt > src/graphics/kitty_diacritics.rs
"""

import hashlib
import sys

UCD_VERSION = "6.0.0"
UCD_SHA256 = "90b45b777346bef027556f9c6cb3ea5d7d745bd60d6762855c08d8a22d34f771"
EXCLUDED = {
    0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, 0x0308, 0x0309, 0x030A,
    0x030B, 0x030C, 0x030F, 0x0311, 0x0313, 0x0314, 0x0342, 0x0653, 0x0654,
}
EXPECTED_LEN = 297


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != UCD_SHA256:
        print(f"UnicodeData.txt sha256 {digest} != pinned UCD {UCD_VERSION} {UCD_SHA256}",
              file=sys.stderr)
        return 1
    table = []
    for line in data.decode("ascii").splitlines():
        f = line.split(";")
        cp = int(f[0], 16)
        if f[2] == "Mn" and f[3] == "230" and f[4] == "NSM" and f[5] == "" \
                and cp not in EXCLUDED:
            table.append(cp)
    if len(table) != EXPECTED_LEN:
        print(f"rule produced {len(table)} entries, expected {EXPECTED_LEN}", file=sys.stderr)
        return 1
    out = [
        "// @generated by scripts/gen_kitty_diacritics.py from Unicode "
        f"{UCD_VERSION} UnicodeData.txt",
        f"// (sha256 {UCD_SHA256}). Do not edit by hand.",
        "",
        "/// Row/column diacritics for kitty Unicode image placeholders: entry `n` encodes",
        "/// row or column `n`. Regenerated clean-room from the UCD; see the generator.",
        f"pub(crate) const ROWCOLUMN_DIACRITICS: [char; {EXPECTED_LEN}] = [",
    ]
    # One entry per line: this is the layout rustfmt keeps, so the output is fmt-clean.
    out.extend(f"    '\\u{{{cp:04X}}}'," for cp in table)
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
